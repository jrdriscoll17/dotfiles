#!/usr/bin/env python3
"""Global theme switcher.

One palette per theme lives in themes/<name>.json. Everything else on this
box is generated from it, so a theme is defined in exactly one place:

    theme list          # show the themes and which one is live
    theme icons         # rebuild the icon index (after installing apps)
    theme recolor <base> <#hex> <name>   # a Material-Black set in any colour
    theme set <name>    # switch to it
    theme apply         # re-render the current theme (run at Hyprland start)
    theme next          # cycle

Generated files carry a "GENERATED by ~/.config/theme" header. Editing them
directly is pointless — the next switch overwrites them. Edit the JSON, then
`theme apply`.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

HOME = Path.home()
CONF = HOME / ".config"
ROOT = CONF / "theme"
THEMES = ROOT / "themes"
STATE = ROOT / "current"
WALLPAPERS = CONF / "hypr" / "wallpapers"
CACHE = HOME / ".cache" / "theme"

BANNER = "GENERATED by ~/.config/theme — edit themes/{name}.json and run `theme apply`."


# -- helpers -----------------------------------------------------------------


def load(name: str) -> dict:
    path = THEMES / f"{name}.json"
    if not path.exists():
        die(f"no such theme: {name}\navailable: {', '.join(names())}")
    theme = json.loads(path.read_text())
    theme["_banner"] = BANNER.format(name=name)
    return theme


def names() -> list[str]:
    return sorted(p.stem for p in THEMES.glob("*.json"))


def current() -> str:
    if STATE.exists():
        name = STATE.read_text().strip()
        if name in names():
            return name
    return names()[0]


def die(msg: str) -> None:
    print(f"theme: {msg}", file=sys.stderr)
    sys.exit(1)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def run(*cmd: str, check: bool = False) -> subprocess.CompletedProcess | None:
    """Best-effort side effect. A missing binary or a dead daemon is not fatal:
    the file on disk is already correct, so the next start picks it up."""
    if not shutil.which(cmd[0]):
        return None
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=15, check=check)
    except (subprocess.SubprocessError, OSError) as exc:
        print(f"theme: {cmd[0]}: {exc}", file=sys.stderr)
        return None


def sub_line(path: Path, pattern: str, replacement: str) -> None:
    """Rewrite one setting in a config we don't own outright."""
    if not path.exists():
        return
    text = path.read_text()
    new, n = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if n:
        path.write_text(new)


def set_ini_key(path: Path, section: str, key: str, value: str) -> None:
    """Set key=value in an ini file, creating the file, the section or the key
    as needed. sub_line() alone silently does nothing when the key is absent,
    which is how a config can end up stranded on the previous theme."""
    line = f"{key}={value}"
    text = path.read_text() if path.exists() else ""

    if re.search(rf"^{re.escape(key)}=", text, re.MULTILINE):
        text = re.sub(rf"^{re.escape(key)}=.*$", line, text, flags=re.MULTILINE)
    elif re.search(rf"^\[{re.escape(section)}\]", text, re.MULTILINE):
        text = re.sub(rf"^(\[{re.escape(section)}\])", rf"\1\n{line}", text, count=1, flags=re.MULTILINE)
    else:
        text = f"{text.rstrip()}\n\n[{section}]\n{line}\n".lstrip()

    write(path, text)


def strip_hash(c: str) -> str:
    return c.lstrip("#")


def rgba(c: str, a: float) -> str:
    """Hyprland's rgba(RRGGBBAA)."""
    return f"rgba({strip_hash(c)}{round(a * 255):02x})"


