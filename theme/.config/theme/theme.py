def render_gtk(t: dict) -> None:
    g = t["gtk"]

    for version in ("gtk-3.0", "gtk-4.0"):
        path = CONF / version / "settings.ini"
        set_ini_key(path, "Settings", "gtk-theme-name", g["theme"])
        set_ini_key(path, "Settings", "gtk-icon-theme-name", g["icons"])
        set_ini_key(path, "Settings", "gtk-application-prefer-dark-theme", "1")

    # GTK2 is still around (a few Xfce and Wine-adjacent dialogs) and reads a
    # completely separate file. nwg-look owns the header and includes
    # .gtkrc-2.0.mine, so keep both conventions intact and only retarget the
    # theme lines.
    gtkrc = HOME / ".gtkrc-2.0"
    if gtkrc.exists():
        sub_line(gtkrc, r'^gtk-theme-name=.*$', f'gtk-theme-name="{g["theme"]}"')
        sub_line(gtkrc, r'^gtk-icon-theme-name=.*$', f'gtk-icon-theme-name="{g["icons"]}"')
    else:
        write(
            gtkrc,
            f'# {t["_banner"]}\n'
            f'gtk-theme-name="{g["theme"]}"\n'
            f'gtk-icon-theme-name="{g["icons"]}"\n'
            'gtk-font-name="Ubuntu Nerd Font 11"\n',
        )

    # libadwaita/GTK4 apps ignore the theme name and read this file directly.
    #
    # The Material-Black themes are GTK2/3 only, so gtk4 names a separate theme
    # to borrow the GTK4 sheet from — a Colloid variant in the same palette. The
    # handful of GTK4 apps therefore stay in-palette even though they can't have
    # the Material-Black look.
    theme_dir = theme_search(g.get("gtk4") or g["theme"])
    for css in ("gtk.css", "gtk-dark.css"):
        dst = CONF / "gtk-4.0" / css
        src = theme_dir / "gtk-4.0" / css if theme_dir else None
        if dst.is_symlink() or dst.exists():
            dst.unlink()
        if src and src.exists():
            dst.symlink_to(src)


def theme_search(name: str) -> Path | None:
    for root in (HOME / ".themes", HOME / ".local/share/themes", Path("/usr/share/themes")):
        if (root / name).is_dir():
            return root / name
    return None


KVANTUM_BASE = Path("/usr/share/Kvantum/Nordic-Darker-Solid")


def render_qt(t: dict) -> None:
    """Qt apps go through Kvantum. No upstream Kvantum theme matches these
    palettes, so each one reuses a stock theme's SVG (the widget shapes) with
    its [GeneralColors] block rewritten — which is the part that reads as the
    theme."""
    c, g = t["colors"], t["gtk"]
    name = g["kvantum"]
    dest = CONF / "Kvantum" / name
    base_conf = KVANTUM_BASE / f"{KVANTUM_BASE.name}.kvconfig"

    if base_conf.exists():
        dest.mkdir(parents=True, exist_ok=True)
        svg = dest / f"{name}.svg"
        if not svg.exists():
            shutil.copy(KVANTUM_BASE / f"{KVANTUM_BASE.name}.svg", svg)

        colors = f"""[GeneralColors]
window.color={c["base"]}
base.color={c["dim"]}
alt.base.color={c["surface"]}
button.color={c["surface"]}
light.color={c["surfaceBright"]}
mid.light.color={c["surface"]}
dark.color={c["dim"]}
mid.color={c["outline"]}
highlight.color={c["accent"]}
inactive.highlight.color={c["surfaceBright"]}
text.color={c["fg"]}
window.text.color={c["fg"]}
button.text.color={c["fg"]}
disabled.text.color={c["fgFaint"]}
tooltip.text.color={c["fg"]}
highlight.text.color={c["dim"]}
link.color={c["accent"]}
link.visited.color={c["purple"]}
progress.indicator.text.color={c["fg"]}
"""
        text = base_conf.read_text()
        text = re.sub(r"\[GeneralColors\]\n(?:[^\[]*)", colors, text, count=1)
        write(dest / f"{name}.kvconfig", f"# {t['_banner']}\n{text}")

    set_ini_key(CONF / "Kvantum" / "kvantum.kvconfig", "General", "theme", name)

    # qt5ct/qt6ct: create the config if it isn't there. Beyond the icon theme,
    # this is what gives Qt an icon theme *at all* — Quickshell included, since
    # Hyprland exports QT_QPA_PLATFORMTHEME=qt6ct to everything it starts.
    for qt in ("qt5ct", "qt6ct"):
        conf = CONF / qt / f"{qt}.conf"
        set_ini_key(conf, "Appearance", "icon_theme", g["icons"])
        set_ini_key(conf, "Appearance", "style", "kvantum")
        set_ini_key(conf, "Appearance", "standard_dialogs", "default")


# Order matters: render_quickshell writes the file Quickshell watches, and the
# hot reload that follows tears down the QML engine — which kills the `theme
# set` process the picker spawned. Doing it last means everything else has
# already landed. ThemeState.qml also detaches the process; belt and braces.
RENDERERS = (
    render_icons,
    render_kitty,
    render_alacritty,
    render_nvim,
    render_doom,
    render_hypr,
    render_btop,
    render_gtk,
    render_qt,
    render_quickshell,
)


def set_wallpaper(path: Path) -> bool:
    """Point every output at `path`, and make sure it actually took.

    This hyprpaper build (0.8.4) only accepts `wallpaper` and `listactive` —
    `preload`, `unload` and `reload` all answer "invalid hyprpaper request". So
    an image that isn't already in memory can't be preloaded: the first
    `wallpaper` request kicks off an async load, returns success, and leaves the
    old wallpaper up. That's what made a theme switch appear to need doing
    twice. Re-issue until listactive agrees, which costs one extra call once the
    image is warm.
    """
    target = str(path)

    for attempt in range(24):
        # Re-issue only at the start and once more if it's clearly stuck: each
        # request makes hyprpaper decode the image again, which is what made a
        # switch spin the fans.
        if attempt in (0, 12):
            run("hyprctl", "hyprpaper", "wallpaper", f",{target}")

        active = run("hyprctl", "hyprpaper", "listactive")
        # Lines look like "DP-1: /path/to.jpg"; hyprctl's own diagnostics
        # ("error: can't send: ...") also contain a colon, so match the shape.
        paths = re.findall(r"^\S+: (/.*)$", active.stdout if active else "", re.MULTILINE)
        if paths and all(p.strip() == target for p in paths):
            return True

        # No monitors listed at all means hyprpaper isn't up — it starts
        # alongside `theme apply` at login. It reads the generated
        # hyprpaper.conf when it does come up, so there is nothing to retry.
        if not paths:
            return False

        # Decoding a 4K JPEG takes a moment; poll rather than nag.
        time.sleep(0.1)

    print(f"theme: hyprpaper did not switch to {path.name}", file=sys.stderr)
    return False



# -- live reload -------------------------------------------------------------


def reload_all(t: dict) -> None:
    c, g = t["colors"], t["gtk"]

    # Hyprland window borders. hyprland.lua does not read the palette, so these
    # are pushed live and re-pushed from autostart via `theme apply`.
    #
    # `hyprctl keyword` is refused outright by a Lua config ("keyword can't work
    # with non-legacy parsers"); `eval` runs a string against the same hl API the
    # config uses.
    run(
        "hyprctl",
        "eval",
        "hl.config({ general = { col = {"
        f' active_border = "{rgba(c["accent"], 0.93)}",'
        f' inactive_border = "{rgba(c["base"], 0.67)}"'
        " } } })",
    )
    set_wallpaper(WALLPAPERS / t["wallpaper"])

    # Notifications are drawn by the shell now, so there is no daemon to
    # reload: the cards read Theme.* and follow the hot-reloaded palette.
    #
    # kitty reloads its config on SIGUSR1; alacritty and quickshell watch their
    # own files, so they need nothing.
    run("pkill", "-USR1", "-x", "kitty")

    # GTK4/libadwaita and anything using the settings portal read gsettings,
    # not settings.ini.
    # Cursor theme is deliberately absent: it isn't part of any of these
    # palettes, and switching themes shouldn't change the pointer.
    for key, value in (
        ("gtk-theme", g["theme"]),
        ("icon-theme", g["icons"]),
        ("color-scheme", "prefer-dark"),
    ):
        run("gsettings", "set", "org.gnome.desktop.interface", key, value)



# -- commands ----------------------------------------------------------------


def apply(name: str, quiet: bool = False) -> None:
    t = load(name)
    for render in RENDERERS:
        render(t)
    STATE.write_text(name + "\n")
    reload_all(t)
    if not quiet:
        print(f"theme: {t['label']}")


def cmd_list() -> None:
    live = current()
    for name in names():
        t = load(name)
        mark = "*" if name == live else " "
        print(f" {mark} {name:<10} {t['label']:<12} {t['blurb']}")


def cmd_data() -> None:
    """Everything the Quickshell picker needs, in one read."""
    print(
        json.dumps(
            {
                "current": current(),
                "themes": [
                    {
                        "name": t["name"],
                        "label": t["label"],
                        "blurb": t["blurb"],
                        "colors": t["colors"],
                        "wallpaper": str(WALLPAPERS / t["wallpaper"]),
                    }
                    for t in (load(n) for n in names())
                ],
            }
        )
    )


def main(argv: list[str]) -> None:
    cmd = argv[0] if argv else "list"

    if cmd in ("list", "-l", "--list"):
        cmd_list()
    elif cmd == "data":
        cmd_data()
    elif cmd == "recolor":
        # Build a Material-Black + Suru-GLOW pair in an arbitrary colour.
        import recolor
        recolor.main(argv[1:])
    elif cmd == "icons":
        # Force the icon index to be rebuilt — after installing new apps or
        # changing the icon theme by hand.
        marker = CONF / "quickshell" / "generated" / "icons.theme"
        if marker.exists():
            marker.unlink()
        for cached in CACHE.glob("icons-*.json"):
            cached.unlink()
        apply(current())
    elif cmd == "current":
        print(current())
    elif cmd == "apply":
        apply(current(), quiet="--quiet" in argv)
    elif cmd == "next":
        all_names = names()
        apply(all_names[(all_names.index(current()) + 1) % len(all_names)])
    elif cmd in ("set", "-s"):
        if len(argv) < 2:
            die("set: need a theme name")
        apply(argv[1])
    elif cmd in names():
        apply(cmd)
    elif cmd in ("-h", "--help", "help"):
        print(__doc__)
    else:
        die(f"unknown command: {cmd}\ntry: theme list")


if __name__ == "__main__":
    main(sys.argv[1:])
