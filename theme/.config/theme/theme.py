#
# Each takes the theme dict and writes files; live-reload side effects go at
# the end of apply() so a dry file render stays cheap.


def render_quickshell(t: dict) -> None:
    c = t["colors"]
    lines = "\n".join(f'\treadonly property color {k}: "{v}"' for k, v in c.items())
    write(
        CONF / "quickshell" / "generated" / "Colors.qml",
        f"""pragma Singleton

import Quickshell
import QtQuick

// {t["_banner"]}
//
// Theme.qml aliases these, so every widget keeps reading Theme.<colour> and
// only this file changes when the theme does. Quickshell watches its config
// directory, so writing this hot-reloads the bar.
Singleton {{
\treadonly property string themeName: "{t["name"]}"
\treadonly property string themeLabel: "{t["label"]}"

{lines}
}}
""",
    )


ICON_ROOTS = (
    HOME / ".local/share/icons",
    HOME / ".icons",
    Path("/usr/share/icons"),
)
# Categories worth indexing: app launchers, notification icons, tray icons.
ICON_CATEGORIES = ("apps", "status", "devices", "places", "actions", "categories")


def icon_theme_chain(name: str) -> list[Path]:
    """A theme plus whatever it inherits, in lookup order, ending at hicolor."""
    chain: list[Path] = []
    seen: set[str] = set()
    queue = [name, "hicolor"]

    while queue:
        theme = queue.pop(0)
        if theme in seen:
            continue
        seen.add(theme)

        for root in ICON_ROOTS:
            directory = root / theme
            if not directory.is_dir():
                continue
            chain.append(directory)
            index = directory / "index.theme"
            if index.exists():
                for line in index.read_text(errors="ignore").splitlines():
                    if line.startswith("Inherits="):
                        queue.extend(p.strip() for p in line.split("=", 1)[1].split(","))
    return chain


def render_icons(t: dict) -> None:
    """Index icon-name -> file, because Qt inside Quickshell has no icon theme.

    Setting one needs a platform theme plugin (qt6ct or the gtk one), neither of
    which is installed, so `Quickshell.iconPath()` and `image://icon/...` only
    ever resolve absolute paths. The shell reads this index instead; see
    services/Icons.qml.
    """
    out = CONF / "quickshell" / "generated" / "icons.json"
    marker = out.with_suffix(".theme")
    icon_theme = t["gtk"]["icons"]

    if out.exists() and marker.exists() and marker.read_text().strip() == icon_theme:
        return

    # Each theme has its own icon set, so a naive rebuild costs ~1.6s of disk
    # walking on every single switch. Cached per icon theme, that becomes a
    # 2.5MB copy. `theme icons` clears the cache when new apps are installed.
    cache = CACHE / f"icons-{icon_theme}.json"
    if cache.exists():
        write(out, cache.read_text())
        write(marker, icon_theme + "\n")
        return

    index: dict[str, str] = {}

    def add(path: Path) -> None:
        index.setdefault(path.stem, str(path))

    def size_rank(name: str) -> tuple[int, int]:
        """Bigger (and scalable) wins: a 512px source beats a 16px one for a
        34px notification badge."""
        if name.startswith("scalable"):
            return (1, 0)
        head = name.split("x")[0].split("@")[0]
        return (0, int(head) if head.isdigit() else 0)

    for theme_dir in icon_theme_chain(t["gtk"]["icons"]):
        # Two layouts in the wild: Papirus nests size/category, the Suru themes
        # nest category/size. Walk both by checking which half of each pair
        # names a category.
        for outer in sorted(
            (d for d in theme_dir.iterdir() if d.is_dir()), key=lambda d: size_rank(d.name), reverse=True
        ):
            if outer.name in ICON_CATEGORIES:
                inner_dirs = sorted(
                    (d for d in outer.iterdir() if d.is_dir()), key=lambda d: size_rank(d.name), reverse=True
                )
            else:
                inner_dirs = [outer / category for category in ICON_CATEGORIES]

            for directory in inner_dirs:
                if not directory.is_dir():
                    continue
                for icon in directory.iterdir():
                    if icon.suffix in (".svg", ".png", ".xpm"):
                        add(icon)

    # Legacy drop-box a lot of third-party packages still use.
    pixmaps = Path("/usr/share/pixmaps")
    if pixmaps.is_dir():
        for icon in pixmaps.iterdir():
            if icon.suffix in (".svg", ".png", ".xpm"):
                add(icon)

    payload = json.dumps(index, separators=(",", ":"), sort_keys=True)
    write(out, payload)
    write(cache, payload)
    write(marker, icon_theme + "\n")


